import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export type DoctorBin = 'vue-doctor' | 'nuxt-doctor';

export interface AgentHooksOptions {
  readonly projectRoot: string;
  readonly bin: DoctorBin;
}

export interface AgentHookWrite {
  readonly path: string;
  readonly content: string;
}

interface ClaudeHookHandler {
  readonly type?: string;
  readonly command?: string;
  readonly [key: string]: unknown;
}

interface ClaudeHookGroup {
  readonly matcher?: string;
  readonly hooks?: readonly ClaudeHookHandler[];
  readonly [key: string]: unknown;
}

interface ClaudeSettings {
  readonly hooks?: Record<string, readonly ClaudeHookGroup[]>;
  readonly [key: string]: unknown;
}

interface CursorHookHandler {
  readonly command?: string;
  readonly timeout?: number;
  readonly [key: string]: unknown;
}

interface CursorHooksConfig {
  readonly version?: number;
  readonly hooks?: Record<string, readonly CursorHookHandler[]>;
  readonly [key: string]: unknown;
}

/** Seconds Cursor waits for the stop hook before giving up. */
export const AGENT_HOOK_TIMEOUT_SECONDS = 120;
/** Follow-up turns a Cursor stop hook may trigger before it stays quiet. */
export const AGENT_HOOK_MAX_CONTINUATIONS = 1;

export function claudeHookCommand(bin: DoctorBin): string {
  return `node "$CLAUDE_PROJECT_DIR/.claude/hooks/${bin}.mjs"`;
}

export function cursorHookCommand(bin: DoctorBin): string {
  return `node .cursor/hooks/${bin}.mjs`;
}

function readJson<T>(path: string): T {
  if (!existsSync(path)) return {} as T;
  const text = readFileSync(path, 'utf8').trim();
  if (text.length === 0) return {} as T;
  try {
    return JSON.parse(text) as T;
  } catch {
    throw new Error(
      `could not parse ${path}: invalid JSON. Fix it and re-run install --agent-hooks.`,
    );
  }
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/**
 * The end-of-turn hook script (react.doctor 0.9.13 behavior). It runs the
 * doctor on the files changed in the working tree; on findings it asks the
 * agent to keep going (Claude Code `Stop` → `{ decision: 'block' }`, Cursor
 * `stop` → `{ followup_message }`) with the report on stdout. Clean runs,
 * doctor errors (exit 2), a missing runner, or a re-entrant stop exit 0
 * silently so the hook can never wedge the agent.
 */
export function buildAgentHookScript(
  bin: DoctorBin,
  event: 'Stop' | 'stop',
): string {
  const args = '--diff --fail-on warn --no-dead-code --format agent';
  return `// Generated by ${bin} install --agent-hooks. Re-run it to update.
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const HOOK_EVENT = ${JSON.stringify(event)};
const MAX_CONTINUATIONS = ${AGENT_HOOK_MAX_CONTINUATIONS};
const MAX_BUFFER = 16 * 1024 * 1024;
const here = dirname(fileURLToPath(import.meta.url));

function readInput() {
  try {
    return JSON.parse(readFileSync(0, 'utf8') || '{}');
  } catch {
    return {};
  }
}

function shouldScan(input) {
  if (HOOK_EVENT === 'Stop') return !input.stop_hook_active;
  if (input.status && input.status !== 'completed') return false;
  const loops = Number(input.loop_count);
  return !Number.isFinite(loops) || loops < MAX_CONTINUATIONS;
}

function runDoctor() {
  const localBin = process.platform === 'win32'
    ? 'node_modules\\\\.bin\\\\${bin}.cmd'
    : './node_modules/.bin/${bin}';
  const commands = [
    ...(existsSync(localBin) ? [localBin + ' ${args}'] : []),
    '${bin} ${args}',
    'pnpm dlx @geoql/${bin}@latest ${args}',
    'npx --yes @geoql/${bin}@latest ${args}',
  ];
  for (const command of commands) {
    const result = spawnSync(command, {
      encoding: 'utf8',
      shell: true,
      maxBuffer: MAX_BUFFER,
    });
    if (result.error || result.status === 127 || result.status === 9009) continue;
    return { status: result.status, output: result.stdout || '' };
  }
  return { status: 0, output: '' };
}

const input = readInput();
if (!shouldScan(input)) process.exit(0);
try {
  process.chdir(process.env.CLAUDE_PROJECT_DIR || join(here, '..', '..'));
} catch {
  process.exit(0);
}
const { status, output } = runDoctor();
// Only exit 1 means findings; 0 is clean and 2 is a doctor/tooling error
// (bad flag, not a git checkout) that the agent cannot fix by editing code.
if (status !== 1 || !output.trim()) process.exit(0);
const message =
  '${bin} found issues in the changed files. Fix them before finishing; for findings you cannot fix now, explain why.\\n\\n' +
  output.trim();
console.log(
  JSON.stringify(
    HOOK_EVENT === 'Stop'
      ? { decision: 'block', reason: message }
      : { followup_message: message },
  ),
);
`;
}

function isManaged(command: string | undefined, managed: string): boolean {
  return command === managed;
}

/**
 * Plan the Claude Code + Cursor hook files. Existing settings are merged,
 * never replaced: only our own hook entries are stripped and re-added (so a
 * re-run is idempotent), every other key, event, and hook survives.
 */
export function planAgentHooks(options: AgentHooksOptions): AgentHookWrite[] {
  const { projectRoot, bin } = options;
  const writes: AgentHookWrite[] = [];

  const claudeSettingsPath = join(projectRoot, '.claude', 'settings.json');
  const claudeCommand = claudeHookCommand(bin);
  const settings = readJson<ClaudeSettings>(claudeSettingsPath);
  const claudeHooks = { ...(settings.hooks ?? {}) };
  const stop = (claudeHooks.Stop ?? []).flatMap((group) => {
    const hooks = group.hooks ?? [];
    const kept = hooks.filter(
      (hook) => !isManaged(hook.command, claudeCommand),
    );
    if (kept.length === hooks.length) return [group];
    return kept.length > 0 ? [{ ...group, hooks: kept }] : [];
  });
  stop.push({ hooks: [{ type: 'command', command: claudeCommand }] });
  claudeHooks.Stop = stop;
  writes.push({
    path: claudeSettingsPath,
    content: json({ ...settings, hooks: claudeHooks }),
  });
  writes.push({
    path: join(projectRoot, '.claude', 'hooks', `${bin}.mjs`),
    content: buildAgentHookScript(bin, 'Stop'),
  });

  const cursorConfigPath = join(projectRoot, '.cursor', 'hooks.json');
  const cursorCommand = cursorHookCommand(bin);
  const cursor = readJson<CursorHooksConfig>(cursorConfigPath);
  const cursorHooks = { ...(cursor.hooks ?? {}) };
  const cursorStop = (cursorHooks.stop ?? []).filter(
    (handler) => !isManaged(handler.command, cursorCommand),
  );
  cursorStop.push({
    command: cursorCommand,
    timeout: AGENT_HOOK_TIMEOUT_SECONDS,
  });
  cursorHooks.stop = cursorStop;
  writes.push({
    path: cursorConfigPath,
    content: json({
      ...cursor,
      version: cursor.version ?? 1,
      hooks: cursorHooks,
    }),
  });
  writes.push({
    path: join(projectRoot, '.cursor', 'hooks', `${bin}.mjs`),
    content: buildAgentHookScript(bin, 'stop'),
  });

  return writes;
}

/** Write the planned hook files, creating parent directories. */
export function writeAgentHooks(writes: readonly AgentHookWrite[]): void {
  for (const write of writes) {
    mkdirSync(dirname(write.path), { recursive: true });
    writeFileSync(write.path, write.content, 'utf8');
  }
}
